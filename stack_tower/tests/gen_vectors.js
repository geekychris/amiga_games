// gen_vectors.js - plays scripted games with the browser's stack-tower-core.js
// (moves, turns, holds and hard drops only, so gravity's floating-point timing
// doesn't come into it) and writes tests/vectors.h for the C port to match.
//
//   node tests/gen_vectors.js /path/to/stack-tower-core.js > tests/vectors.h
const S = require(process.argv[2]);
const games = [['marathon', 12345], ['marathon', 987654321], ['dig', 42], ['dig', 2026]];
const out = [];
for (const [mode, seed] of games) {
  const g = S.newGame({ mode, seed });
  let k = 0;
  for (; k < 120 && !g.over && !g.won; k++) {
    const r = (k * 7 + seed) % 5, m = ((k * 13 + seed) % 9) - 4;
    if (k % 11 === 5) S.hold(g);
    for (let i = 0; i < r; i++) S.rotate(g, i % 2 ? -1 : 1);
    for (let i = 0; i < Math.abs(m); i++) S.move(g, Math.sign(m));
    S.hardDrop(g);
  }
  let h = 2166136261;
  for (const v of g.board) { h ^= v; h = Math.imul(h, 16777619); }
  out.push({ mode, seed, pieces: k, score: g.score, lines: g.lines, over: g.over ? 1 : 0, won: g.won ? 1 : 0,
             board: h >>> 0, queue: S.preview(g, 5), hold: g.hold == null ? -1 : g.hold });
}
console.log('// generated by tests/gen_vectors.js from the browser\'s stack-tower-core.js');
console.log('static const struct { int mode; unsigned long seed; int pieces; long score; int lines, over, won; unsigned long board; int queue[5]; int hold; } vectors[] = {');
for (const v of out)
  console.log(`    { ${v.mode === 'dig' ? 'MODE_DIG' : 'MODE_MARATHON'}, ${v.seed}UL, ${v.pieces}, ${v.score}L, ${v.lines}, ${v.over}, ${v.won}, ${v.board}UL, { ${v.queue.join(', ')} }, ${v.hold} },`);
console.log('};');
