"""make_title.py - turn a modern title image into Terra Strike's main screen.

  python3 tools/make_title.py SOURCE.png [--dither none|fs] [--out title_image.c]
                              [--preview preview.png]

Steps: scale to 320x256 lores PAL, pick 32 colours (median cut), snap them to
the 12-bit OCS/ECS palette, make pen 0 the darkest colour (the border), remap
the pixels, and write the image as five 40-byte-per-row bitplanes in a C file
the game links in. The preview shows the source and the Amiga result side by
side, scaled up 3x with square pixels.
"""
import argparse
import os
from PIL import Image

W, H, DEPTH = 320, 256, 5
NCOL = 1 << DEPTH

ap = argparse.ArgumentParser()
ap.add_argument("source")
ap.add_argument("--dither", choices=("none", "fs"), default="none")
ap.add_argument("--out", default="title_image.c")
ap.add_argument("--preview", default="")
opt = ap.parse_args()

src = Image.open(opt.source).convert("RGB")
img = src.resize((W, H), Image.LANCZOS)

# 1. choose 32 colours. Posterize to the 12-bit OCS/ECS gamut first, then run
# k-means over the distinct colours weighted by sqrt(pixel count): plain median
# cut spends the palette on the big sea and grass areas and washes out the
# small saturated details (logo bands, craft, explosion, tanks).
import numpy as np
arr = (np.asarray(img, dtype=np.int32) >> 4)                 # 0..15 per gun
keys = arr[..., 0] * 256 + arr[..., 1] * 16 + arr[..., 2]
uniq, counts = np.unique(keys, return_counts=True)
pts = np.stack([uniq >> 8, (uniq >> 4) & 15, uniq & 15], 1).astype(np.float64)
wts = np.sqrt(counts.astype(np.float64))
rng = np.random.default_rng(1987)
# k-means++ seeding
cent = [pts[np.argmax(wts)]]
for _ in range(1, NCOL):
    d = np.min(((pts[:, None, :] - np.array(cent)[None]) ** 2).sum(-1), 1) * wts
    cent.append(pts[rng.choice(len(pts), p=d / d.sum())] if d.sum() > 0 else pts[0])
cent = np.array(cent)
for _ in range(40):
    lab = np.argmin(((pts[:, None, :] - cent[None]) ** 2).sum(-1), 1)
    for k in range(NCOL):
        m = lab == k
        if m.any():
            cent[k] = (pts[m] * wts[m, None]).sum(0) / wts[m].sum()
cols = sorted({tuple(int(round(v)) for v in c) for c in cent},
              key=lambda c: c[0] * 3 + c[1] * 6 + c[2])        # darkest first: pen 0 = border
if (0, 0, 0) not in cols:
    cols[0] = (0, 0, 0)                                        # true black for the sky and border
while len(cols) < NCOL:
    cols.append((0, 0, 0))

# 2. remap the image onto the snapped palette
pimg = Image.new("P", (1, 1))
flat = []
for r, g, b in cols:
    flat += [r * 17, g * 17, b * 17]
pimg.putpalette(flat + [0] * (768 - len(flat)))
final = img.quantize(palette=pimg, dither=Image.Dither.FLOYDSTEINBERG if opt.dither == "fs"
                     else Image.Dither.NONE)
pix = final.load()

# 3. chunky -> planar
planes = [bytearray(W // 8 * H) for _ in range(DEPTH)]
for y in range(H):
    for x in range(W):
        c = pix[x, y]
        for p in range(DEPTH):
            if c >> p & 1:
                planes[p][y * (W // 8) + x // 8] |= 0x80 >> (x & 7)


def nearest(rgb):
    return min(range(NCOL), key=lambda i: sum((cols[i][k] * 17 - rgb[k]) ** 2 for k in range(3)))


pen_text, pen_shadow, pen_white = nearest((255, 238, 0)), nearest((0, 0, 0)), nearest((255, 255, 255))

with open(opt.out, "w") as f:
    f.write("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Chris Collins <chris@hitorro.com>\n\n")
    f.write(f"/* title_image.c - generated by tools/make_title.py from {os.path.basename(opt.source)}\n"
            f" * ({src.width}x{src.height} -> {W}x{H}, {NCOL} colours, dither {opt.dither}). Do not edit. */\n")
    f.write('#include "title_image.h"\n\n')
    f.write(f"const unsigned short title_palette[{NCOL}] = {{\n")
    for i in range(0, NCOL, 8):
        f.write("    " + ", ".join(f"0x{r:X}{g:X}{b:X}" for r, g, b in cols[i:i + 8]) + ",\n")
    f.write("};\n\n")
    f.write(f"const unsigned char title_planes[{DEPTH}][{W // 8 * H}] = {{\n")
    for p in range(DEPTH):
        f.write("  {\n")
        data = planes[p]
        for i in range(0, len(data), 20):
            f.write("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",\n")
        f.write("  },\n")
    f.write("};\n")

with open(os.path.join(os.path.dirname(opt.out) or ".", "title_image.h"), "w") as f:
    f.write("// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Chris Collins <chris@hitorro.com>\n\n"
            "/* title_image.h - main screen bitmap (generated, see tools/make_title.py) */\n"
            "#ifndef TITLE_IMAGE_H\n#define TITLE_IMAGE_H\n\n"
            f"#define TITLE_W {W}\n#define TITLE_H {H}\n#define TITLE_DEPTH {DEPTH}\n"
            f"#define TITLE_PEN_TEXT {pen_text}      /* nearest to yellow */\n"
            f"#define TITLE_PEN_SHADOW {pen_shadow}    /* nearest to black */\n"
            f"#define TITLE_PEN_WHITE {pen_white}     /* nearest to white */\n\n"
            f"extern const unsigned short title_palette[{NCOL}];\n"
            f"extern const unsigned char title_planes[{DEPTH}][{W // 8 * H}];\n\n#endif\n")

if opt.preview:
    a = src.resize((W * 3, H * 3), Image.LANCZOS)
    b = final.convert("RGB").resize((W * 3, H * 3), Image.NEAREST)
    sheet = Image.new("RGB", (W * 6 + 12, H * 3), (16, 20, 24))
    sheet.paste(a, (0, 0))
    sheet.paste(b, (W * 3 + 12, 0))
    sheet.save(opt.preview)

used = len(set(final.get_flattened_data())) if hasattr(final, 'get_flattened_data') else len(set(final.getdata()))
print(f"{opt.out}: {W}x{H}, {used}/{NCOL} pens used, text pen {pen_text} "
      f"{cols[pen_text]}, shadow pen {pen_shadow}, dither {opt.dither}")
