"""make_font.py - the AmigaOS 4 text font: DejaVu Sans Mono Bold rendered
into 16 x 16 cells (the classic Amiga's topaz 8 at twice the resolution:
the same 8 x 8 cell in the games' coordinates, the baseline on row 12),
stretched across the cell, written as a C header.

DejaVu fonts are under the Bitstream Vera licence, which allows this.

  python3 tools/make_font.py [path/to/DejaVuSansMono-Bold.ttf] > a3d_font16.h
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont


def find_font():
    if len(sys.argv) > 1:
        return sys.argv[1]
    import matplotlib
    return os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSansMono-Bold.ttf")


# rendered large, then squeezed into the cell: stretched across (a monospace
# glyph is narrow, and centred it would look letter-spaced), 1 px apart
font = ImageFont.truetype(find_font(), 30)
adv = ImageFont.truetype(find_font(), 30).getlength("M")
rows = []
for code in range(32, 127):
    big = Image.new("L", (int(adv) + 2, 32), 0)
    d = ImageDraw.Draw(big)
    d.text((1, 24), chr(code), font=font, fill=255, anchor="ls")      # baseline on row 24 of 32
    small = big.resize((15, 16), Image.LANCZOS)
    px = small.load()
    bits = []
    for y in range(16):
        v = 0
        for x in range(15):
            if px[x, y] >= 100:
                v |= 0x8000 >> x
        bits.append(v)
    rows.append((code, bits))

print("/* a3d_font16.h - generated by tools/make_font.py from DejaVu Sans Mono Bold")
print(" * (Bitstream Vera licence); do not edit. Characters 32..126, 16 rows of 16")
print(" * pixels each, bit 15 left, the baseline on row 12. */")
print("static const uint16_t a3_font16[95][16] = {")
for code, bits in rows:
    name = {"\\": "backslash", "/": "slash", "*": "star"}.get(chr(code), chr(code))
    print("    { " + ", ".join("0x%04X" % b for b in bits) + " },   /* " + name + " */")
print("};")
