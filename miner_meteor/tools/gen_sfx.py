"""
Generate miner_meteor's sound effects as signed 8-bit mono PCM tables
(sfx_data.h / sfx_data.cpp). No dependencies beyond the standard library.

The effects reproduce the Atari Lynx port's (lynxdev/games/miner_meteor/
src/sound.c), which plays them on Mikey: square-wave note lists and an
LFSR noise burst, ticked at the game's 50 Hz. Here the same notes are
rendered offline, at the Lynx's quantised pitches, with Mikey's +/-volume
square and its 12-bit LFSR noise:

  jump       G4 C5 E5           2+2+3 frames, volume 40
  key        E6 A6              3+6 frames, volume 60
  levelwin   C5 E5 G5 C6        5+5+5+12 frames, volume 60
  gameover   G4 F4 Eb4 C4       10+10+10+24 frames, volume 60
  win        C5 E5 G5 C6 - G5 C6  6+6+6+8, 4 rest, 5+20 frames, volume 60
  death      noise pitch 5, volume 100, -4 a frame (25 frames)
  land       (not in the Lynx port) noise pitch 7, volume 48, -12 a frame

The rate is a whole Paula period (PAL clock / 222 = 15977 Hz), so the
68k build plays them at their pitch and AHI gets the same frequency.

  python3 tools/gen_sfx.py               # writes sfx_data.h / sfx_data.cpp
  python3 tools/gen_sfx.py --wav DIR     # also writes DIR/<name>.wav to listen
"""
import argparse
import os
import struct
import wave

PAULA_PAL = 3546895
PERIOD = 222
RATE = PAULA_PAL // PERIOD           # 15977 Hz
FRAME_HZ = 50                        # the Lynx port ticks sound at 50 Hz
GAIN_NUM, GAIN_DEN = 5, 4            # Lynx volume (0..127) -> sample amplitude

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.dirname(HERE)


def lynx_hz(hz):
    """The frequency SND_PERIOD(hz) really plays on Mikey (lynxsnd.h)."""
    sel = (0 if hz >= 1954 else 1 if hz >= 977 else 2 if hz >= 489 else
           3 if hz >= 245 else 4 if hz >= 123 else 5 if hz >= 62 else 6)
    q = (500000 >> sel) // max(hz, 16)
    bkup = 0xFF if q > 255 else q - 1
    return (1000000 >> sel) / (2.0 * (bkup + 1))


def amp(vol):
    return min(127, vol * GAIN_NUM // GAIN_DEN)


def frames_to_samples(start_frame, n):
    """Samples covering frames [start, start+n), without rounding drift."""
    a = start_frame * RATE // FRAME_HZ
    b = (start_frame + n) * RATE // FRAME_HZ
    return b - a


def notes(seq, vol):
    """A Lynx note list: (hz, frames); hz 0 = rest."""
    out, frame, phase = [], 0, 0.0
    a = amp(vol)
    for hz, n in seq:
        count = frames_to_samples(frame, n)
        frame += n
        if not hz:
            out += [0] * count
            phase = 0.0
            continue
        step = lynx_hz(hz) / RATE
        for _ in range(count):
            out.append(a if phase < 0.5 else -a)
            phase = (phase + step) % 1.0
    return out


def noise(pitch, vol, decay):
    """snd_noise(): Mikey's 12-bit LFSR with taps 0,1,4,5 (FEED 0x33),
    shift register 0x5A (+ CTLB's 0x10 in bits 8-11), clocked at
    500 kHz / (4 + pitch*8 + 1); the volume falls by `decay` a frame."""
    shift = 0x15A
    clock = 500000.0 / (4 + (pitch << 3) + 1)
    step = clock / RATE
    acc, out, frame, v = 0.0, [], 0, vol
    bit = 0
    while v > 0:
        for _ in range(frames_to_samples(frame, 1)):
            acc += step
            while acc >= 1.0:
                acc -= 1.0
                fb = ((shift >> 0) ^ (shift >> 1) ^ (shift >> 4) ^ (shift >> 5)) & 1
                bit = fb ^ 1                      # Mikey's feedback is inverted
                shift = ((shift << 1) | bit) & 0xFFF
            a = amp(v)
            out.append(a if bit else -a)
        frame += 1
        v -= decay
    return out


EFFECTS = [
    ("jump",     notes([(392, 2), (523, 2), (659, 3)], 40)),
    ("land",     noise(7, 48, 12)),
    ("key",      notes([(1319, 3), (1760, 6)], 60)),
    ("death",    noise(5, 100, 4)),
    ("levelwin", notes([(523, 5), (659, 5), (784, 5), (1047, 12)], 60)),
    ("gameover", notes([(392, 10), (349, 10), (311, 10), (262, 24)], 60)),
    ("win",      notes([(523, 6), (659, 6), (784, 6), (1047, 8), (0, 4),
                        (784, 5), (1047, 20)], 60)),
]


def write_sources():
    pcm, offsets = [], []
    for _, s in EFFECTS:
        offsets.append(len(pcm))
        s = list(s) + [0] * (2 + (len(s) & 1))   # end silent, even length (Paula words)
        pcm += s
    offsets.append(len(pcm))

    names = [n for n, _ in EFFECTS]
    hdr = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Chris Collins <chris@hitorro.com>",
        "",
        "/* Generated by tools/gen_sfx.py - do not edit. */",
        "#ifndef MINER_METEOR_SFX_DATA_H",
        "#define MINER_METEOR_SFX_DATA_H",
        "",
        "#define SFX_RATE    %dL     /* Hz: PAL Paula clock / SFX_PERIOD */" % RATE,
        "#define SFX_PERIOD  %d" % PERIOD,
        "",
        "enum {",
    ]
    hdr += ["    SFX_%s," % n.upper() for n in names]
    hdr += [
        "    SFX_COUNT",
        "};",
        "",
        "/* signed 8-bit mono; effect i is sfx_pcm[sfx_offset[i] .. sfx_offset[i+1]) */",
        "extern const signed char   sfx_pcm[];",
        "extern const unsigned long sfx_offset[SFX_COUNT + 1];",
        "#define SFX_PCM_BYTES %dL" % len(pcm),
        "",
        "#endif",
        "",
    ]
    src = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Chris Collins <chris@hitorro.com>",
        "",
        "/* Generated by tools/gen_sfx.py - do not edit. */",
        '#include "sfx_data.h"',
        "",
        "const unsigned long sfx_offset[SFX_COUNT + 1] = {",
        "    " + ", ".join("%dUL" % o for o in offsets),
        "};",
        "",
        "const signed char sfx_pcm[%d] = {" % len(pcm),
    ]
    for i, (name, _) in enumerate(EFFECTS):
        src.append("    /* %s: %d samples, %.0f ms */" % (
            name, offsets[i + 1] - offsets[i], 1000.0 * (offsets[i + 1] - offsets[i]) / RATE))
        chunk = pcm[offsets[i]:offsets[i + 1]]
        for j in range(0, len(chunk), 20):
            src.append("    " + ",".join(str(v) for v in chunk[j:j + 20]) + ",")
    src += ["};", ""]

    with open(os.path.join(OUT_DIR, "sfx_data.h"), "w") as f:
        f.write("\n".join(hdr))
    with open(os.path.join(OUT_DIR, "sfx_data.cpp"), "w") as f:
        f.write("\n".join(src))
    print("sfx_data.{h,cpp}: %d effects, %d bytes at %d Hz" % (len(EFFECTS), len(pcm), RATE))


def write_wavs(d):
    os.makedirs(d, exist_ok=True)
    for name, s in EFFECTS:
        with wave.open(os.path.join(d, name + ".wav"), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(1)
            w.setframerate(RATE)
            w.writeframes(bytes((v + 128) & 0xFF for v in s))   # WAV 8-bit is unsigned


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--wav", metavar="DIR", help="also write one .wav per effect")
    args = ap.parse_args()
    write_sources()
    if args.wav:
        write_wavs(args.wav)


if __name__ == "__main__":
    main()
