// gen_vectors.js - test vectors from the browser game's own core
// (boing-pinball-core.js): the collision functions on fixed inputs and
// short flights on Comet Tour, written to vectors.h for test_cases.c.
//   node tests/gen_vectors.js /path/to/boing-pinball-core.js > tests/vectors.h
'use strict';
const P = require(process.argv[2]);
const out = [];
const f = v => String(Math.round(v * 65536));      // 16.16 fixed point: the 68k build has no floating point

// capsule segments: ball (x, y, vx, vy) against a (ax, ay)-(bx, by) radius r, restitution e
const segs = [
  [100, 116, -300, -900, 50, 100, 150, 100, 3, 0.45],
  [52, 300, -1200, 200, 40, 200, 40, 400, 4, 0.4],
  [210, 330, 400, -2500, 100, 345, 150, 192, 5, 0.6],
  [77, 230, 0, -50, 58, 190, 150, 132, 4, 0.45],
  [300, 610, 30, -40, 280, 600, 320, 600, 3, 0.45],
];
out.push('static const int32_t seg_vec[][14] = {   /* ball x y vx vy, seg ax ay bx by r e, result x y vx vy (imp in [14]) */');
const segRes = [];
for (const [x, y, vx, vy, ax, ay, bx, by, r, e] of segs) {
  const b = { x, y, vx, vy };
  const imp = P.hitSegment(b, { a: [ax, ay], b: [bx, by], r, e });
  out.push(`  { ${[x, y, vx, vy, ax, ay, bx, by, r, e, b.x, b.y, b.vx, b.vy].map(f).join(', ')} },`);
  segRes.push(imp);
}
out.push('};');
out.push(`static const int32_t seg_imp[] = { ${segRes.map(f).join(', ')} };`);

// flippers: pivot (0,0), len 80, r1 11, r2 6.5, angle, angular velocity; the ball
const flips = [[60, 21.5, 0, 0, 0, 30], [40, 22, 0, -800, 0.2, 0], [70, 17, 200, -1500, -0.3, 42], [20, -25, 0, 900, 0, -26]];
out.push('static const int32_t flip_vec[][10] = {   /* ball x y vx vy, ang w, result x y vx vy */');
for (const [x, y, vx, vy, ang, w] of flips) {
  const b = { x, y, vx, vy };
  P.hitFlipper(b, { px: 0, py: 0, len: 80, r1: 11, r2: 6.5, ang, w });
  out.push(`  { ${[x, y, vx, vy, ang, w, b.x, b.y, b.vx, b.vy].map(f).join(', ')} },`);
}
out.push('};');

// circles
const circs = [[188, 676, 0, -200, 188, 700, 24, 0.5], [70, 470, -900, 300, 50, 470, 6, 0.5]];
out.push('static const int32_t circ_vec[][12] = {   /* ball x y vx vy, c x y r e, result x y vx vy */');
for (const [x, y, vx, vy, cx, cy, r, e] of circs) {
  const b = { x, y, vx, vy };
  P.hitCircle(b, { c: [cx, cy], r, e });
  out.push(`  { ${[x, y, vx, vy, cx, cy, r, e, b.x, b.y, b.vx, b.vy].map(f).join(', ')} },`);
}
out.push('};');

// short flights on Comet Tour (well away from the parts the Amiga version changed)
// (no pop bumpers: a hair's difference in where a ball meets one sends it somewhere else)
const flights = [[240, 520, 0, 1800, 0.35], [140, 280, -600, -300, 0.25], [354, 520, 0, 2500, 0.2], [100, 300, -1000, 800, 0.3], [400, 450, 600, -400, 0.4], [239, 300, 0, -100, 0.5]];
out.push('static const int32_t flight_vec[][7] = {   /* x y vx vy steps (not fixed), result x y */');
for (const [x, y, vx, vy, secs] of flights) {
  const w = new P.World();
  const b = w.addBall(x, y, vx, vy);
  for (let t = 0; t < Math.round(secs * 120); t++) w.step(P.STEP);
  out.push(`  { ${[f(x), f(y), f(vx), f(vy), Math.round(secs * 120), f(b.x), f(b.y)].join(', ')} },`);
}
out.push('};');
console.log('/* vectors.h - generated by tests/gen_vectors.js from the browser game\'s core; do not edit. 16.16 fixed point */');
console.log(out.join('\n'));
